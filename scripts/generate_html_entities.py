"""Generate crates/core/src/html/entities.rs from the WHATWG named character references.

Usage: python3 scripts/generate_html_entities.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "scripts" / "html_entities.json"
TARGET = ROOT / "crates" / "core" / "src" / "html" / "entities.rs"


def rust_string(codepoints):
    return "".join(f"\\u{{{cp:x}}}" for cp in codepoints)


def main():
    table = json.loads(SOURCE.read_text())
    # Byte order, which `binary_search` relies on.
    entries = sorted((name.removeprefix("&"), entry["codepoints"]) for name, entry in table.items())

    lines = [
        "// @generated by scripts/generate_html_entities.py from scripts/html_entities.json. Do not edit.",
        "",
        "/// Named character references without the leading `&`, sorted by name.",
        "/// Names ending in `;` are complete references; the others are legacy forms",
        "/// that may appear without a terminating semicolon.",
        "#[rustfmt::skip]",
        f"pub(super) static ENTITIES: [(&str, &str); {len(entries)}] = [",
    ]
    lines += [f'    ("{name}", "{rust_string(codepoints)}"),' for name, codepoints in entries]
    lines += ["];", ""]
    TARGET.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
